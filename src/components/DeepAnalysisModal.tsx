import React, { useState } from 'react';
import { Sparkles, Copy, Check, X, FileText, Download, Scale } from 'lucide-react';
import ReactMarkdown from 'react-markdown';

interface DeepAnalysisModalProps {
  isOpen: boolean;
  title: string;
  analysisText: string;
  type: 'defense' | 'opposing';
  onClose: () => void;
}

export const DeepAnalysisModal: React.FC<DeepAnalysisModalProps> = ({
  isOpen,
  title,
  analysisText,
  type,
  onClose,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const handleCopy = () => {
    navigator.clipboard.writeText(analysisText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 bg-black/60 z-50 flex items-center justify-center p-3 sm:p-4 overflow-y-auto">
      <div className="bg-white rounded-2xl max-w-3xl w-full p-6 space-y-4 my-8 shadow-2xl border border-slate-200 max-h-[92vh] flex flex-col">
        {/* Header */}
        <div className="flex items-center justify-between border-b pb-3 shrink-0">
          <div className="flex items-center gap-2.5">
            <div className={`p-2 rounded-lg ${type === 'defense' ? 'bg-amber-100 text-amber-800' : 'bg-rose-100 text-rose-800'}`}>
              <Sparkles className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-slate-900 font-serif">
                {type === 'defense' ? 'Evidentiary Hardening & Admissibility Report' : 'Rebuttal & Discrediting Strategy Report'}
              </h3>
              <p className="text-xs text-slate-500 truncate max-w-md">
                Subject: <strong className="text-slate-800">{title}</strong>
              </p>
            </div>
          </div>

          <button onClick={onClose} className="text-slate-400 hover:text-slate-700 p-1">
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Markdown Content Area */}
        <div className="flex-1 overflow-y-auto p-4 bg-slate-50 rounded-xl border border-slate-200/80 text-sm leading-relaxed text-slate-800 font-sans space-y-2 prose prose-sm prose-slate max-w-none [&>h3]:text-base [&>h3]:font-bold [&>h3]:text-slate-900 [&>h3]:mt-3 [&>h4]:text-sm [&>h4]:font-bold [&>h4]:text-slate-800 [&>ul]:list-disc [&>ul]:pl-5 [&>ol]:list-decimal [&>ol]:pl-5">
          <ReactMarkdown>{analysisText}</ReactMarkdown>
        </div>

        {/* Footer Actions */}
        <div className="flex items-center justify-between pt-2 border-t shrink-0">
          <div className="text-[11px] text-slate-400">
            Generated by Project Innocence Legal Reasoning Engine
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-100 border border-slate-200 rounded-lg transition-colors"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-600" />
                  <span className="text-emerald-600">Copied</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy Report</span>
                </>
              )}
            </button>

            <button
              onClick={onClose}
              className="px-4 py-1.5 text-xs font-semibold text-white bg-slate-800 hover:bg-slate-900 rounded-lg transition-colors"
            >
              Close
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
